-- 20261022090608_customer_approval_requests.sql — the approval request in the database
--
-- CUSTOMER_APPROVAL.md, WP2, migration B. The workflow the vault note
-- `Customer approval` describes, as far as the database carries it:
--
--   * product_approval_requests — one row per round of asking: the files, the
--     employee's message, one private link (stored as the SHA-256 of its
--     token), one expiry, one decision. A rework is a new row; the old stays.
--   * product_approval_request_files — the files of a round, with the path of
--     the copy the customer's page serves from the private bucket
--     `approval-proofs`.
--   * products.approved_request_id — the round an approved product went into
--     production on.
--   * create_approval_request / settle_approval_request /
--     withdraw_approval_request — the only ways the request tables are
--     written (they have no write policies). The create RPC is one
--     transaction: the request, its files, the product moving to
--     AWAITING_APPROVAL, the history entry and the queued mail commit together
--     or not at all.
--   * fn_approval_request_closed — one AFTER UPDATE trigger owns every
--     consequence of a request leaving PENDING: the product's status, the
--     stock booking on an approval, the history entry, the notice mail. The
--     writers change the request's status and nothing else.
--   * fn_production_deductions — the stock a product's release books, computed
--     here as the client computes it, so the trigger can book without the app.
--   * The guards: a waiting product's spec and settings are locked, and a
--     product is in AWAITING_APPROVAL exactly while it has a PENDING request.
--
-- The three mails this lands (approval-request, approval-decided,
-- approval-withdrawn) get their email_settings rows here, with their default
-- wording; the templates are supabase/functions/send-email/templates/.
-- approval-expired, queued on the EXPIRED branch below, lands with WP6
-- together with the only writer that reaches that branch.

