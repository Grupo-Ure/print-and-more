-- ── Guards ───────────────────────────────────────────────────────────────────
-- A waiting product is locked like a released one: the customer must never
-- look at files that changed underneath them. The two lock guards of
-- 20261008175931 gain AWAITING_APPROVAL; two new ones lock the settings and
-- tie the status to the request. All keep the actor exemption: postgres /
-- supabase_admin run the seed, service_role is the e2e runner, and the
-- functions above run as the owner.

CREATE OR REPLACE FUNCTION "public"."fn_refuse_released_product_spec_change"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" = ''
    AS $$
BEGIN
  IF current_user IN ('postgres', 'supabase_admin', 'service_role') THEN
    RETURN NEW;
  END IF;

  IF OLD.status IN ('AWAITING_APPROVAL', 'IN_PRODUCTION', 'DONE')
     AND (NEW.department, NEW.type, NEW.quantity, NEW.notes)
         IS DISTINCT FROM (OLD.department, OLD.type, OLD.quantity, OLD.notes) THEN
    RAISE EXCEPTION
      'Product (%) has been released (%); its specification is locked',
      OLD.id, OLD.status;
  END IF;

  RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION "public"."fn_refuse_released_product_child_change"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" = ''
    AS $$
DECLARE
  parent_id uuid;
  parent_status public.product_status;
BEGIN
  IF current_user IN ('postgres', 'supabase_admin', 'service_role') THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    parent_id := OLD.product_id;
  ELSE
    parent_id := NEW.product_id;
  END IF;

  SELECT status INTO parent_status
  FROM public.products WHERE id = parent_id;

  IF parent_status IN ('AWAITING_APPROVAL', 'IN_PRODUCTION', 'DONE') THEN
    RAISE EXCEPTION
      'Product (%) has been released (%); its specification is locked',
      parent_id, parent_status;
  END IF;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

