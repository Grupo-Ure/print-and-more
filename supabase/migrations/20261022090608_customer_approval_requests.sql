/**
 * Trigger guard: a product is in AWAITING_APPROVAL exactly while it has a
 * PENDING request. Refuses AWAITING_APPROVAL without one, and any other
 * status while one is PENDING — the request closing is the only way out.
 * The create RPC and the closing trigger run as the owner and pass.
 *
 * @trigger BEFORE UPDATE OF status ON products (per row), when the status changes
 */
CREATE OR REPLACE FUNCTION "public"."fn_refuse_awaiting_without_request"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" = ''
    AS $$
DECLARE
  has_pending boolean;
BEGIN
  IF current_user IN ('postgres', 'supabase_admin', 'service_role') THEN
    RETURN NEW;
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM public.product_approval_requests r
    WHERE r.product_id = NEW.id AND r.status = 'PENDING'
  ) INTO has_pending;

  IF NEW.status = 'AWAITING_APPROVAL' AND NOT has_pending THEN
    RAISE EXCEPTION
      'Product (%) has no open approval request; only create_approval_request moves it to AWAITING_APPROVAL',
      NEW.id;
  END IF;

  IF NEW.status <> 'AWAITING_APPROVAL' AND has_pending THEN
    RAISE EXCEPTION
      'Product (%) is awaiting customer approval; the request has to close before it moves',
      NEW.id;
  END IF;

  RETURN NEW;
END;
$$;

ALTER FUNCTION "public"."fn_refuse_awaiting_without_request"() OWNER TO "postgres";

CREATE TRIGGER "trg_refuse_awaiting_without_request"
    BEFORE UPDATE OF status ON "public"."products"
    FOR EACH ROW
    WHEN (OLD."status" IS DISTINCT FROM NEW."status")
    EXECUTE FUNCTION "public"."fn_refuse_awaiting_without_request"();
