-- ── fn_approval_request_closed ───────────────────────────────────────────────

/**
 * Every consequence of a request leaving PENDING, in the same transaction as
 * the status change that closed it. The product is waiting by construction
 * (a PENDING request and AWAITING_APPROVAL always go together).
 *
 *   APPROVED            the product goes into production on this round: its
 *                       stock is booked with the shortage allowed — the
 *                       customer cannot be shown a stock error, so a short
 *                       target is floored at zero and named in the history
 *                       entry —, approved_request_id is set, the product moves
 *                       to IN_PRODUCTION; history CUSTOMER_APPROVAL_GRANTED
 *                       and an automatic PRODUCTION_READY_SET; the assignee
 *                       is told (approval-decided).
 *   CHANGES_REQUESTED   back to PREPRESS; history with the note; the assignee
 *                       is told (approval-decided).
 *   EXPIRED             back to PREPRESS; history; the shop is told
 *                       (approval-expired — its template and the only writer
 *                       that reaches this branch land with WP6).
 *   WITHDRAWN           back to PREPRESS; history; the customer is told the
 *                       link no longer works (approval-withdrawn), unless the
 *                       request was never mailed.
 *
 * Runs as the owner, so the product's move passes the lock guards and
 * fn_refuse_awaiting_without_request; the status update fires
 * fn_assign_stage_default_assignee as any release does. `by` in the history
 * meta is the settling employee's id, or CUSTOMER for the page and the
 * expiry; history.user_id carries the same employee, or null.
 *
 * @trigger AFTER UPDATE OF status ON product_approval_requests (per row), when the row leaves PENDING
 */
CREATE OR REPLACE FUNCTION "public"."fn_approval_request_closed"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" = ''
    AS $$
DECLARE
  product       RECORD;
  by_whom       text;
  file_ids      jsonb;
  deductions    jsonb;
  booking       jsonb := jsonb_build_object('ok', true, 'shortages', '[]'::jsonb);
BEGIN
  by_whom := COALESCE(NEW.settled_by::text, 'CUSTOMER');

  SELECT p.id, p.order_id, o.order_number
  INTO product
  FROM public.products p
  JOIN public.orders o ON o.id = p.order_id
  WHERE p.id = NEW.product_id
  FOR UPDATE OF p;

  SELECT COALESCE(jsonb_agg(f.file_id), '[]'::jsonb) INTO file_ids
  FROM public.product_approval_request_files f
  WHERE f.request_id = NEW.id;

  IF NEW.status = 'APPROVED' THEN
    deductions := public.fn_production_deductions(product.id);
    IF jsonb_array_length(deductions) > 0 THEN
      booking := public.book_production_deductions(
        deductions,
        'Automatic on production release ' || product.order_number,
        true
      );
    END IF;

    UPDATE public.products
    SET status = 'IN_PRODUCTION', approved_request_id = NEW.id
    WHERE id = product.id;

    INSERT INTO public.history (order_id, product_id, event_type, user_id, meta)
    VALUES (
      product.order_id, product.id, 'CUSTOMER_APPROVAL_GRANTED', NEW.settled_by,
      jsonb_build_object(
        'request_id', NEW.id, 'round', NEW.round, 'by', by_whom, 'note', NEW.note,
        'file_ids', file_ids, 'shortages', booking->'shortages'
      )
    );
    INSERT INTO public.history (order_id, product_id, event_type, user_id, meta)
    VALUES (
      product.order_id, product.id, 'PRODUCTION_READY_SET', NEW.settled_by,
      jsonb_build_object('automatic', true, 'request_id', NEW.id)
    );

    PERFORM public.queue_email('approval-decided', product.order_id, product.id, jsonb_build_object('request_id', NEW.id));

  ELSIF NEW.status = 'CHANGES_REQUESTED' THEN
    UPDATE public.products SET status = 'PREPRESS' WHERE id = product.id;

    INSERT INTO public.history (order_id, product_id, event_type, user_id, meta)
    VALUES (
      product.order_id, product.id, 'CUSTOMER_APPROVAL_CHANGES_REQUESTED', NEW.settled_by,
      jsonb_build_object('request_id', NEW.id, 'round', NEW.round, 'by', by_whom, 'note', NEW.note)
    );

    PERFORM public.queue_email('approval-decided', product.order_id, product.id, jsonb_build_object('request_id', NEW.id));

  ELSIF NEW.status = 'EXPIRED' THEN
    UPDATE public.products SET status = 'PREPRESS' WHERE id = product.id;

    INSERT INTO public.history (order_id, product_id, event_type, user_id, meta)
    VALUES (
      product.order_id, product.id, 'CUSTOMER_APPROVAL_EXPIRED', NULL,
      jsonb_build_object('request_id', NEW.id, 'round', NEW.round)
    );

    PERFORM public.queue_email('approval-expired', product.order_id, product.id, jsonb_build_object('request_id', NEW.id));

  ELSIF NEW.status = 'WITHDRAWN' THEN
    UPDATE public.products SET status = 'PREPRESS' WHERE id = product.id;

    INSERT INTO public.history (order_id, product_id, event_type, user_id, meta)
    VALUES (
      product.order_id, product.id, 'CUSTOMER_APPROVAL_WITHDRAWN', NEW.settled_by,
      jsonb_build_object('request_id', NEW.id, 'round', NEW.round, 'by', by_whom)
    );

    IF NEW.mailed THEN
      PERFORM public.queue_email('approval-withdrawn', product.order_id, product.id, jsonb_build_object('request_id', NEW.id));
    END IF;
  END IF;

  RETURN NULL;
END;
$$;

