/**
 * Records the customer's answer by hand — the customer called or walked in.
 * Moves a PENDING request to APPROVED or CHANGES_REQUESTED, stamps who
 * recorded it and when; everything that follows on the product is
 * fn_approval_request_closed's. A request for changes needs a note, as it
 * does on the customer's page. Refuses a request that is not PENDING.
 */
CREATE OR REPLACE FUNCTION "public"."settle_approval_request"(
    "request_id" "uuid",
    "decision" "public"."approval_request_status",
    "note" "text" DEFAULT NULL
) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" = ''
    AS $$
DECLARE
  actor           uuid := auth.uid();
  current_status  public.approval_request_status;
  clean_note      text := NULLIF(btrim(settle_approval_request.note), '');
BEGIN
  IF actor IS NULL THEN
    RAISE EXCEPTION 'settle_approval_request: a signed-in user is required';
  END IF;
  IF settle_approval_request.decision NOT IN ('APPROVED', 'CHANGES_REQUESTED') THEN
    RAISE EXCEPTION 'settle_approval_request: the decision must be APPROVED or CHANGES_REQUESTED';
  END IF;
  IF settle_approval_request.decision = 'CHANGES_REQUESTED' AND clean_note IS NULL THEN
    RAISE EXCEPTION 'settle_approval_request: a request for changes needs a note';
  END IF;

  SELECT r.status INTO current_status
  FROM public.product_approval_requests r
  WHERE r.id = settle_approval_request.request_id
  FOR UPDATE;

  IF current_status IS NULL THEN
    RAISE EXCEPTION 'settle_approval_request: request % does not exist', settle_approval_request.request_id;
  END IF;
  IF current_status <> 'PENDING' THEN
    RAISE EXCEPTION 'settle_approval_request: request % is % and no longer pending', settle_approval_request.request_id, current_status;
  END IF;

  UPDATE public.product_approval_requests
  SET status = settle_approval_request.decision,
      note = clean_note,
      responded_at = now(),
      settled_by = actor
  WHERE id = settle_approval_request.request_id;
END;
$$;

