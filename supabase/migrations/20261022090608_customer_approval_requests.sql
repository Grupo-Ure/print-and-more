-- ── book_production_deductions: nested-call safe ─────────────────────────────
-- Same body as the catalog migration's, with its tables schema-qualified and
-- search_path pinned: it is now called from fn_approval_request_closed, whose
-- empty search_path would otherwise stay in effect inside it and leave
-- `stamp_models` unresolved (the same lesson audit.sql notes for the history
-- guard). The signature, owner and grants are unchanged.

CREATE OR REPLACE FUNCTION "public"."book_production_deductions"("deductions" "jsonb", "note" "text", "allow_shortage" boolean DEFAULT false) RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" = ''
    AS $$
DECLARE
  item        RECORD;
  prev_stock  INTEGER;
  deducted    INTEGER;
  shortages   JSONB := '[]'::JSONB;
BEGIN
  FOR item IN
    SELECT
      d->>'target'              AS target,
      (d->>'id')::uuid          AS id,
      (d->>'quantity')::integer AS quantity
    FROM jsonb_array_elements(deductions) AS d
    ORDER BY d->>'target', d->>'id'
  LOOP
    IF item.target NOT IN ('STAMP', 'TEXTILE') THEN
      RAISE EXCEPTION 'unknown deduction target %', item.target;
    END IF;
    IF item.quantity IS NULL OR item.quantity < 1 THEN
      RAISE EXCEPTION 'invalid deduction quantity for %', item.id;
    END IF;

    IF item.target = 'STAMP' THEN
      SELECT stock INTO prev_stock FROM public.stamp_models WHERE id = item.id FOR UPDATE;
    ELSE
      -- prev_stock holds the *available* amount: declared samples are excluded
      SELECT stock - sample_stock INTO prev_stock FROM public.textile_variants WHERE id = item.id FOR UPDATE;
    END IF;

    IF prev_stock IS NULL OR prev_stock < item.quantity THEN
      shortages := shortages || jsonb_build_object(
        'target', item.target,
        'id', item.id,
        'required', item.quantity,
        'available', COALESCE(prev_stock, 0)
      );
    END IF;

    -- Missing row: nothing to deduct. Under allow_shortage = false any update
    -- is rolled back by the shortage exception below, so deducting the full
    -- quantity here is safe either way.
    CONTINUE WHEN prev_stock IS NULL;

    deducted := LEAST(prev_stock, item.quantity);
    CONTINUE WHEN deducted = 0;

    IF item.target = 'STAMP' THEN
      UPDATE public.stamp_models SET stock = prev_stock - deducted WHERE id = item.id;
      INSERT INTO public.stamp_stock_movements (model_id, quantity, type, note, user_id)
      VALUES (item.id, deducted, 'AUTO_DEDUCTION', note, auth.uid());
    ELSE
      -- relative decrement: physical pieces leave, the sample count stays
      UPDATE public.textile_variants SET stock = stock - deducted WHERE id = item.id;
      INSERT INTO public.textile_stock_movements (variant_id, quantity, type, note, user_id)
      VALUES (item.id, deducted, 'AUTO_DEDUCTION', note, auth.uid());
    END IF;
  END LOOP;

  IF NOT allow_shortage AND jsonb_array_length(shortages) > 0 THEN
    RAISE EXCEPTION 'INSUFFICIENT_STOCK' USING DETAIL = shortages::text;
  END IF;

  RETURN jsonb_build_object('ok', true, 'shortages', shortages);
END;
$$;

-- ── fn_production_deductions ─────────────────────────────────────────────────

/**
 * The stock deductions a product's release to production books, as the jsonb
 * list book_production_deductions takes: [{target, id, quantity, product_id,
 * line_id?}]. Computed as productionReleaseService.collectStockRequirements
 * computes it in the app — the two must agree:
 *   STAMP:   a model stamp (TRODAT_PRINTY, WOODEN_STAMP) deducts its model
 *            plus, for a catalog ink colour, the matching replacement pad
 *            (the TRODAT_PAD model with the stamp model's replacement pad
 *            article number in that colour); a TRODAT_PAD product deducts
 *            its pad variant. Other stamp types reference no model.
 *   TEXTILE: every shop-supplied garment line with a catalog variant deducts
 *            that variant by the line's own quantity (line_id names the line).
 * A quantity below one counts as one, as the app floors it. Pure read.
 */
CREATE OR REPLACE FUNCTION "public"."fn_production_deductions"("product_id" "uuid") RETURNS "jsonb"
    LANGUAGE "plpgsql" STABLE
    SET "search_path" = ''
    AS $$
DECLARE
  product      RECORD;
  deductions   jsonb := '[]'::jsonb;
  quantity     integer;
  model_id     uuid;
  ink_color    text;
  pad_article  text;
  pad_id       uuid;
  line         RECORD;
BEGIN
  SELECT p.id, p.department, p.type, p.quantity
  INTO product
  FROM public.products p
  WHERE p.id = fn_production_deductions.product_id;

  IF product.id IS NULL THEN
    RAISE EXCEPTION 'fn_production_deductions: product % does not exist', fn_production_deductions.product_id;
  END IF;

  quantity := GREATEST(COALESCE(product.quantity, 1), 1);

  IF product.department = 'STAMP' THEN
    IF product.type IN ('TRODAT_PRINTY', 'WOODEN_STAMP') THEN
      IF product.type = 'TRODAT_PRINTY' THEN
        SELECT c.model_id, c.color INTO model_id, ink_color
        FROM public.trodat_printy_products c WHERE c.product_id = product.id;
      ELSE
        SELECT c.model_id, c.color INTO model_id, ink_color
        FROM public.wooden_stamp_products c WHERE c.product_id = product.id;
      END IF;

      IF model_id IS NOT NULL THEN
        deductions := deductions || jsonb_build_object(
          'target', 'STAMP', 'id', model_id, 'quantity', quantity, 'product_id', product.id
        );

        -- Model stamps ship with a pad in the chosen ink colour: the matching
        -- replacement pad goes too. 'OTHER' has no catalog pad.
        IF ink_color IS NOT NULL AND ink_color <> 'OTHER' THEN
          SELECT NULLIF(btrim(m.replacement_pad_article_number), '') INTO pad_article
          FROM public.stamp_models m WHERE m.id = model_id;

          IF pad_article IS NOT NULL THEN
            SELECT m.id INTO pad_id
            FROM public.stamp_models m
            WHERE m.type = 'TRODAT_PAD' AND m.article_number = pad_article AND m.color = ink_color
            LIMIT 1;

            IF pad_id IS NOT NULL THEN
              deductions := deductions || jsonb_build_object(
                'target', 'STAMP', 'id', pad_id, 'quantity', quantity, 'product_id', product.id
              );
            END IF;
          END IF;
        END IF;
      END IF;
    ELSIF product.type = 'TRODAT_PAD' THEN
      SELECT c.pad_variant_id INTO pad_id
      FROM public.trodat_pad_products c WHERE c.product_id = product.id;

      IF pad_id IS NOT NULL THEN
        deductions := deductions || jsonb_build_object(
          'target', 'STAMP', 'id', pad_id, 'quantity', quantity, 'product_id', product.id
        );
      END IF;
    END IF;
  END IF;

  IF product.department = 'TEXTILE' THEN
    FOR line IN
      SELECT g.id, g.variant_id, g.quantity
      FROM public.textile_garments g
      WHERE g.product_id = product.id
        AND g.origin = 'SHOP_SUPPLIED'
        AND g.variant_id IS NOT NULL
      ORDER BY g.sort_order, g.created_at
    LOOP
      deductions := deductions || jsonb_build_object(
        'target', 'TEXTILE', 'id', line.variant_id, 'quantity', GREATEST(line.quantity, 1),
        'product_id', product.id, 'line_id', line.id
      );
    END LOOP;
  END IF;

  RETURN deductions;
END;
$$;

